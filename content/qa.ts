function buildAnswer(input: AnswerInput) {
  const intent = input.intent ?? answerIntentById[input.id] ?? "general";
  return {
    ...publicActive,
    id: input.id,
    question: input.question,
    standardAnswer: input.standardAnswer,
    limitations: input.limitations,
    claimIds: input.claimIds,
    sourceIds: input.sourceIds,
    requiredClaimIds: input.claimIds,
    requiredSourceIds: input.sourceIds,
    matchKeywords: input.matchKeywords,
    ...(input.matchRequiresProjectContext ? { matchRequiresProjectContext: true } : {}),
    evaluationGoal: input.evaluationGoal,
    exclusivePoints: input.exclusivePoints,
    avoidRepeating: input.avoidRepeating.length ? input.avoidRepeating : ["不编造未公开事实", "不省略口径边界"],
    responseShape: input.responseShape,
    targetLength: { min: Math.max(80, input.targetLength.min), max: Math.min(600, input.targetLength.max) },
    preferredStoryIds: input.preferredStoryIds,
    followUpQuestions: input.followUpQuestions,
    closingPurpose: input.closingPurpose,
    verification: input.verification ?? "self_attested",
    ...(input.relatedProject ? { relatedProject: input.relatedProject } : {}),
    supportsClaimIds: input.claimIds,
    factSkeleton: {
      intent,
      thesis: input.standardAnswer,
      mustInclude: input.mustInclude ?? input.exclusivePoints,
      allowedFacts: input.allowedFacts ?? [input.standardAnswer, ...(input.details ?? [])],
      allowedNumbers: input.allowedNumbers ?? sharedAllowedNumbers,
      allowedOrganizations: input.allowedOrganizations ?? sharedAllowedOrganizations,
      allowedProjectStatuses: input.allowedProjectStatuses ?? sharedAllowedStatuses,
      boundaryTriggers: input.boundaryTriggers ?? sharedBoundaryTriggers,
      forbiddenDetails: input.forbiddenDetails ?? sharedForbiddenDetails,
    },
  };
}

